HEADER = "| Path | Type | Required | Allowed values | Default | Description |\n| --- | --- | --- | --- | --- | --- |"


def render_cell_constraints(row: Row, with_notes: bool = True) -> str:
    lines = list(row.constraints)
    if with_notes:
        lines.extend(row.notes)
    return "<br>".join(lines) if lines else ""


def render_row(row: Row) -> str:
    desc = prose(row.description) if row.description else ""
    if row.when:
        cond = f"Only when {row.when}."
        desc = f"{cond} {desc}".strip()
    cells = [
        code(row.path),
        row.type.replace("|", "\\|"),
        "yes" if row.required else "no",
        render_cell_constraints(row),
        row.default or "",
        desc,
    ]
    return "| " + " | ".join(cells) + " |"


def table(rows: list[Row]) -> str:
    return HEADER + "\n" + "\n".join(render_row(r) for r in rows)


def top_key(path: str) -> str:
    return re.split(r"[.\[]", path, maxsplit=1)[0]


def second_key(path: str) -> str | None:
    """`exposes[].binding.location.path` -> `exposes[].binding`; None for a top-level row."""
    segments = path.split(".")
    if len(segments) < 2:
        return None
    second = segments[1][:-2] if segments[1].endswith("[]") else segments[1]
    return f"{segments[0]}.{second}"


def ordered_top_keys(schema: dict[str, Any]) -> list[str]:
    required = list(schema.get("required", []))
    rest = [k for k in schema.get("properties", {}) if k not in required]
    return required + rest


SINGLES_HEADING = "Single-value fields"


def group_by_top(rows: list[Row]) -> dict[str, list[Row]]:
    by_top: dict[str, list[Row]] = {}
    for row in rows:
        by_top.setdefault(top_key(row.path), []).append(row)
    return by_top


def render_sections(schema: dict[str, Any], rows: list[Row], level_offset: int = 2) -> list[str]:
    """Single-row top-level fields share one table; the rest get a section each."""
    h2 = "#" * level_offset
    h3 = "#" * (level_offset + 1)
    out: list[str] = []
    by_top = group_by_top(rows)
    keys = [k for k in ordered_top_keys(schema) if by_top.get(k)]
    singles = [r for k in keys if len(by_top[k]) == 1 for r in by_top[k]]
    if singles:
        out.append(f"{h2} {SINGLES_HEADING}\n")
        out.append(table(singles) + "\n")
    for key in keys:
        group = by_top[key]
        if len(group) == 1:
            continue
        out.append(f"{h2} {key}\n")
        if len(group) <= SPLIT_ROWS:
            out.append(table(group) + "\n")
            continue
        sizes: dict[str, int] = {}
        for row in group:
            sk = second_key(row.path)
            if sk is not None:
                sizes[sk] = sizes.get(sk, 0) + 1
        head = [r for r in group if second_key(r.path) is None or sizes[second_key(r.path)] == 1]
        if head:
            out.append(table(head) + "\n")
        seen: list[str] = []
        subgroups: dict[str, list[Row]] = {}
        for row in group:
            sk = second_key(row.path)
            if sk is None or sizes[sk] == 1:
                continue
            if sk not in subgroups:
                seen.append(sk)
            subgroups.setdefault(sk, []).append(row)
        for sk in seen:
            out.append(f"{h3} `{sk}`\n")
            out.append(table(subgroups[sk]) + "\n")
    return out


def overview_table(schema: dict[str, Any], rows: list[Row]) -> str:
    by_top = group_by_top(rows)
    tops = {r.path: r for r in rows if "." not in r.path and "[" not in r.path}
    lines = ["| Field | Type | Required |", "| --- | --- | --- |"]
    for key in ordered_top_keys(schema):
        row = tops.get(key)
        if row is None:
            continue
        target = _anchor(SINGLES_HEADING) if len(by_top[key]) == 1 else _anchor(key)
        lines.append(f"| [{code(key)}](#{target}) | {row.type} | {'yes' if row.required else 'no'} |")
    return "\n".join(lines)


def _anchor(text: str) -> str:
    return re.sub(r"[^a-z0-9_-]+", "-", text.lower()).strip("-")


def frontmatter(title: str, description: str) -> str:
    # JSON strings are valid YAML double-quoted scalars, so a colon in the text is safe.
    return (
        f"---\ntitle: {json.dumps(title, ensure_ascii=False)}\n"
        f"description: {json.dumps(description, ensure_ascii=False)}\n---\n\n{MARKER}\n"
    )


def source_line(src: Source, version: str, digest: str) -> str:
    return (
        f"Generated from `fluid_build/schemas/fluid-schema-{version}.json` in the "
        f"`{PACKAGE}` {src.cli_version} package (sha256 `{digest[:16]}`). "
        "It is the schema `fluid validate` checks a contract against, rendered without edits. "
        "To regenerate: `python scripts/gen_contract_reference.py`."
    )


HOW_TO_READ = (
    "Each table row is one field, addressed by its path from the contract root: "
    "`.` descends into an object, `[]` marks the items of a list, and `<key>` stands for any "
    "key of a map. **Required** means required inside its parent object; the parent can itself "
    "be optional. **Allowed values** lists the enum, pattern and range the schema enforces. "
    "An object typed plainly `object` rejects keys the schema does not list; `object (open)` "
    "accepts extra keys and `object (free-form)` has no listed keys. A row that begins "
    "\"Only when ...\" exists only under that condition. See [how to read this "
    "reference](./README.md#how-to-read-a-row)."
)


def render_stable(src: Source, version: str) -> str:
    schema, digest = load_schema(src, version)
    rows = Walker(schema).walk_root()
    title = f"Contract field reference, schema {version}"
    out = [
        frontmatter(title, f"The fields of the FLUID {version} contract schema (stable): path, type, required, allowed values, default and description."),
        f"# {title}\n",
        f"Status: **stable**. Schema {version} is the newest stable schema bundled with the CLI. "
        f"The newer {', '.join(src.previews)} schema is a preview; see the "
        + ", ".join(f"[{p} preview delta](./contract-{p}-preview.md)" for p in src.previews)
        + ".\n",
        source_line(src, version, digest) + "\n",
        HOW_TO_READ + "\n",
        "## Top-level fields\n",
        overview_table(schema, rows) + "\n",
    ]
    out.extend(render_sections(schema, rows))
    return "\n".join(out).rstrip("\n") + "\n"


def _diff_attr(old: Row, new: Row) -> list[tuple[str, str, str]]:
    changes: list[tuple[str, str, str]] = []
    a, b = old.signature(), new.signature()
    for name in a:
        if a[name] == b[name]:
            continue
        changes.append((name, _fmt_attr(name, a[name]), _fmt_attr(name, b[name])))
    return changes


def _fmt_attr(name: str, value: Any) -> str:
    if name == "required":
        return "yes" if value else "no"
    if name == "allowed values":
        return "<br>".join(value) if value else "none"
    if name == "description":
        return prose(value) if value else "none"
    return str(value) if value not in (None, "") else "none"


def render_preview(src: Source, stable: str, preview: str) -> str:
    old_schema, _ = load_schema(src, stable)
    new_schema, digest = load_schema(src, preview)
    old_rows = Walker(old_schema).walk_root()
    new_walker = Walker(new_schema)
    new_rows = new_walker.walk_root()
    old_by = {r.key: r for r in old_rows}
    new_by = {r.key: r for r in new_rows}
    added = [r for r in new_rows if r.key not in old_by]
    removed = [r for r in old_rows if r.key not in new_by]
    changed = [(old_by[r.key], r) for r in new_rows if r.key in old_by and _diff_attr(old_by[r.key], r)]

    title = f"Contract field reference, schema {preview} preview"
    out = [
        frontmatter(title, f"What the FLUID {preview} preview schema adds to, and changes in, the stable {stable} schema, field by field."),
        f"# {title}\n",
        f"Status: **preview**. A contract opts in with `fluidVersion: \"{preview}\"`; a contract that declares {stable} is unaffected. "
        f"This page lists the difference between the {stable} schema and the {preview} schema as bundled with the CLI: "
        f"added fields, fields whose definition changed, and fields removed. A field not listed here has the same type, "
        f"required flag, allowed values, default and description in both; for those, use the "
        f"[{stable} reference](./contract-{stable}.md). A definition used at several paths is listed once, at its first path.\n",
        source_line(src, preview, digest) + "\n",
        HOW_TO_READ + "\n",
        "## At a glance\n",
        f"- Added: {len(added)} {'row' if len(added) == 1 else 'rows'}\n"
        f"- Changed: {len(changed)} {'row' if len(changed) == 1 else 'rows'}\n"
        f"- Removed: {len(removed)} {'row' if len(removed) == 1 else 'rows'}\n",
    ]
    # Added
    out.append("## Added fields\n")
    if added:
        by_top: dict[str, list[Row]] = {}
        for r in added:
            by_top.setdefault(top_key(r.path), []).append(r)
        for key in ordered_top_keys(new_schema):
            if key in by_top:
                out.append(f"### {key}\n")
                out.append(table(by_top[key]) + "\n")
    else:
        out.append("None.\n")
    # Changed
    out.append("## Changed fields\n")
    if changed:
        out.append(
            "Each row names the attribute that differs and shows both values.\n"
        )
        cl = ["| Path | Attribute | " + stable + " | " + preview + " |", "| --- | --- | --- | --- |"]
        for old, new in changed:
            label = code(new.path) + (f" (only when {new.when})" if new.when else "")
            for attr, before, after in _diff_attr(old, new):
                cl.append(f"| {label} | {attr} | {before} | {after} |")
        out.append("\n".join(cl) + "\n")
    else:
        out.append("None.\n")
    # Removed
    out.append("## Removed fields\n")
    if removed:
        out.append("\n".join(f"- {code(r.path)}" for r in removed) + "\n")
    else:
        out.append(f"None. Every {stable} field path is present in {preview}.\n")
    return "\n".join(out).rstrip("\n") + "\n"


