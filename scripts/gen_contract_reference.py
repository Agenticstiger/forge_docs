def expected_pages(src: Source) -> dict[str, str]:
    pages = {f"contract-{src.stable}.md": render_stable(src, src.stable)}
    for preview in src.previews:
        pages[f"contract-{preview}-preview.md"] = render_preview(src, src.stable, preview)
    return pages


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if committed pages differ")
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = ap.parse_args(argv)

    src = load_source()
    pages = expected_pages(src)
    out_dir: Path = args.out_dir

    if args.check:
        problems = 0
        for name, text in pages.items():
            path = out_dir / name
            if not path.exists():
                print(f"MISSING: {path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path}", file=sys.stderr)
                problems += 1
                continue
            have = path.read_text(encoding="utf-8")
            if have != text:
                problems += 1
                print(f"DRIFT: {path.name} differs from what the installed CLI generates", file=sys.stderr)
                diff = difflib.unified_diff(
                    have.splitlines(), text.splitlines(), "committed", "generated", lineterm="", n=0
                )
                for i, line in enumerate(diff):
                    if i >= 20:
                        print("  ...", file=sys.stderr)
                        break
                    print("  " + line[:200], file=sys.stderr)
        if out_dir.is_dir():
            for path in sorted(out_dir.glob("*.md")):
                if path.name in pages:
                    continue
                if MARKER in path.read_text(encoding="utf-8"):
                    print(f"STALE: {path.name} carries the generated marker but is no longer produced", file=sys.stderr)
                    problems += 1
        if problems:
            print(
                f"FAIL: {problems} reference page problem(s). Run "
                "`python scripts/gen_contract_reference.py` with the pinned CLI and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {len(pages)} generated reference pages match the schemas bundled in {PACKAGE} {src.cli_version}.")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    for path in sorted(out_dir.glob("*.md")):
        if path.name not in pages and MARKER in path.read_text(encoding="utf-8"):
            path.unlink()
            print(f"removed stale {path.name}")
    for name, text in pages.items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
